import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const outputPath = path.join(root, 'docs', 'evidence', 'SOURCE_INVENTORY.json');
const evidenceLedgerPath = path.join(root, 'docs', 'evidence', 'EVIDENCE_LEDGER.md');
const excludedDirectories = new Set(['.git', 'dist', 'node_modules']);
const files = (await walk(root))
  .filter((file) => file !== outputPath && file !== evidenceLedgerPath)
  .sort((left, right) => relative(left).localeCompare(relative(right)));
const inventory = [];

for (const file of files) {
  const content = await readFile(file);
  const filePath = relative(file);
  inventory.push({
    path: filePath,
    bytes: content.byteLength,
    sha256: createHash('sha256').update(content).digest('hex'),
    ...provenanceFor(filePath)
  });
}

const document = {
  schemaVersion: 1,
  product: 'Media Scout Downloader',
  candidateVersion: '3.7.13',
  generatedAt: '2026-08-17',
  license: 'Project code and assets are distributed under LICENSE.md: copyright 2026 Nouraldin Farge, all rights reserved.',
  scope: 'Application/source/test/configuration/assets/documentation and generated sample files. Generated dist/, dependency/tool directories, Git internals, this self-referential output, and the evidence ledger that binds this output hash are excluded.',
  caveat: 'Repository possession and an all-rights-reserved notice do not independently prove authorship. Owner attestation items remain explicit in PROVENANCE.md.',
  files: inventory
};

await writeFile(outputPath, `${JSON.stringify(document, null, 2)}\n`, 'utf8');
console.log(`Generated source/provenance inventory for ${inventory.length} files.`);

async function walk(directory) {
  const output = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isDirectory() && excludedDirectories.has(entry.name)) continue;
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) output.push(...await walk(target));
    else if (entry.isFile()) output.push(target);
  }
  return output;
}

function relative(file) {
  return path.relative(root, file).replace(/\\/g, '/');
}

function provenanceFor(filePath) {
  const common = {
    licenseStatus: 'Covered by repository LICENSE.md (all rights reserved); not an OSI-approved open-source license.',
    aiAssistance: 'AI coding agents assisted with private drafting/review; human owner retains publication and rights responsibility.'
  };
  if (filePath.startsWith('docs/evidence/samples/redacted-report-3.7.13/')) {
    return {
      ...common,
      kind: 'generated-sanitized-evidence',
      origin: 'Generated deterministically by test-harness/generate-sanitized-report-sample.mjs from repository-owned synthetic .invalid-domain data.',
      ownerAttestationRequired: false
    };
  }
  if (filePath.startsWith('assets/icons/')) {
    return {
      ...common,
      kind: 'repository-supplied-raster-asset',
      origin: 'Present in the supplied private repository snapshot; no embedded author, license, or third-party attribution metadata was found.',
      ownerAttestationRequired: true
    };
  }
  if (filePath === 'src/content/mp4-remuxer.js') {
    return {
      ...common,
      kind: 'repository-supplied-remux-source',
      origin: 'Present in the supplied private repository snapshot; no import, bundled dependency, copyright header, or embedded third-party attribution was found. Limited exact-phrase public search found no match but is not proof of originality.',
      ownerAttestationRequired: true
    };
  }
  if (filePath.startsWith('src/')) {
    return {
      ...common,
      kind: 'application-source',
      origin: 'Supplied private repository implementation plus reviewed changes made during the current AI-assisted release-readiness work.',
      ownerAttestationRequired: true
    };
  }
  if (filePath.startsWith('test-harness/')) {
    return {
      ...common,
      kind: 'test-or-build-source',
      origin: 'Supplied private repository tooling or reviewed code added during the current AI-assisted release-readiness work.',
      ownerAttestationRequired: true
    };
  }
  if (filePath === 'package-lock.json') {
    return {
      ...common,
      kind: 'generated-package-metadata',
      origin: 'Generated by npm from package.json; the P0 dependency tree is empty.',
      ownerAttestationRequired: false
    };
  }
  if (filePath.startsWith('.github/')) {
    return {
      ...common,
      kind: 'repository-automation-configuration',
      origin: 'Supplied private repository configuration, reviewed locally; referenced actions are external at CI runtime and require separately pinned provenance.',
      ownerAttestationRequired: true
    };
  }
  if (/\.(?:md|txt)$/i.test(filePath) || filePath.startsWith('docs/')) {
    return {
      ...common,
      kind: 'documentation-or-evidence',
      origin: 'Supplied private documentation or reviewed AI-assisted draft/evidence created from local inspection and cited primary sources.',
      ownerAttestationRequired: true
    };
  }
  return {
    ...common,
    kind: 'repository-configuration',
    origin: 'Supplied private repository configuration plus reviewed current release-readiness changes.',
    ownerAttestationRequired: true
  };
}
